export function hasScenarioVideo(year?: string, qIndex?: number): boolean {
  if (!year || qIndex == null || !Number.isFinite(qIndex)) return false;
  const child = /^cprite\s+(\d{4})$/i.exec(String(year).trim());
  const prefix = child ? `c${child[1]}` : year;
  return VIDEO_IDS.has(`${prefix}-${String(qIndex).padStart(4, "0")}`);
}
export function scenarioVideoIds(): string[] { return [...VIDEO_IDS]; }
